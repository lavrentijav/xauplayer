    // ===== Пасхалка: многократное нажатие на версию =====
    /**
     * Возвращает фразу для количества нажатий на версию (или null, если рано молчать).
     */
    fun versionTap(count: Int): String? = when {
        count < 10 -> null
        count == 10 -> "А зачем ты тыкаешь? 🤔"
        count in 11..13 -> "Нафига ты тыкаешь? Я ничего не дам. 😤"
        count == 14 -> "Серьёзно? Всё ещё тыкаешь? 🙄"
        count in 15..19 -> "Ну может, на 100-й раз что-то будет? 👀"
        count in 20..49 -> "Твоя настойчивость впечатляет... но нет. 🗿"
        count == 50 -> "Половина пути до 100. Ещё не поздно заняться делом. ⏳"
        count in 51..99 -> "Тук-тук-тук... (это не откроет секретов) 🚪"
        count == 100 -> "Нуу... поздравляю тебя с бездарно потраченными несколькими минутами! 🎉🏆 Ачивка «Задрот-тыкальщик» получена."
        else -> "Достижение уже получено. Иди отдохни, чемпион. 😴"
    }

